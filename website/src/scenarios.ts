// Data for the deploy simulator. Everything here is lifted from the real CLI:
// compatibility rules mirror src/domain/services/CompatibilityPolicy.ts, the
// Dockerfiles come from the generator snapshot tests, and the provider configs
// follow src/infrastructure/generators/provider-config/*. If the CLI changes,
// change this file too.

export type ProjectId = 'vite' | 'next' | 'express' | 'fastapi' | 'spring' | 'go' | 'html';
export type ProviderId = 'vercel' | 'netlify' | 'github-pages' | 'railway' | 'render';
type Kind = 'static' | 'server' | 'serverless';
type Lang = 'node' | 'python' | 'java' | 'go' | 'static';

export interface Project {
  id: ProjectId;
  label: string;
  dir: string;
  lang: Lang;
  framework?: string;
  kind: Kind;
  /** What `describeProfile` prints after "Detected". */
  detected: string;
  build?: { command: string; output: string; files: number };
  spa?: boolean;
  /** Env var names in .env.production (server apps only). */
  env?: string[];
  dockerfile: string;
  /** Render native runtime, when Render can build it without Docker. */
  renderNative?: { runtime: string; build: string; start: string };
}

export interface Provider {
  id: ProviderId;
  name: string;
  kinds: Kind[];
  serverlessFrameworks?: string[];
  url: (slug: string) => string;
}

export type Tone = 'plain' | 'muted' | 'ok' | 'step' | 'err' | 'accent' | 'cmd' | 'note';

export type Line =
  | { type: 'cmd'; text: string }
  | { type: 'out'; text: string; tone?: Tone; pause?: number; reveals?: string }
  | { type: 'spin'; text: string; done: string; ms: number; tone?: Tone };

export interface GeneratedFile {
  path: string;
  why: string;
  contents: string;
}

export interface Scenario {
  ok: boolean;
  lines: Line[];
  files: GeneratedFile[];
  /** For incompatible pairs: a provider that would work. */
  suggestion?: ProviderId;
}

