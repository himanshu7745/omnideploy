export function project(id: ProjectId): Project {
  return PROJECTS.find((p) => p.id === id)!;
}

export function provider(id: ProviderId): Provider {
  return PROVIDERS.find((p) => p.id === id)!;
}

const LANG_LABEL: Record<Lang, string> = {
  node: 'Node.js',
  python: 'Python',
  java: 'Java',
  go: 'Go',
  static: 'Static site',
};

function listOf(items: readonly string[]): string {
  return items.length <= 1 ? (items[0] ?? '') : `${items.slice(0, -1).join(', ')} or ${items.at(-1)}`;
}

/** Same rules as checkCompatibility() in the CLI. */
export function compatibility(p: Project, prov: Provider): { ok: true } | { ok: false; reason: string } {
  if (p.kind === 'static') return { ok: true }; // every provider here hosts static sites
  if (p.framework && prov.serverlessFrameworks?.includes(p.framework)) return { ok: true };
  if (!prov.kinds.includes('server')) {
    const what = p.framework ?? LANG_LABEL[p.lang];
    return {
      ok: false,
      reason: prov.serverlessFrameworks?.length
        ? `only hosts static sites and ${listOf(prov.serverlessFrameworks)} apps, not ${what} servers`
        : `only hosts static sites, not ${what} servers`,
    };
  }
  return { ok: true };
}

function renderUsesDocker(p: Project): boolean {
  return p.kind !== 'static' && !p.renderNative;
}

function dockerignore(p: Project): string {
  const extra: Record<Lang, string[]> = {
    node: ['node_modules', 'npm-debug.log*', '.next', '.nuxt', '.output', 'coverage'],
    python: ['__pycache__', '*.pyc', '.venv', 'venv', '.pytest_cache', '.mypy_cache'],
    java: ['target', 'build', '.gradle', '*.iml', '.idea'],
    go: ['bin', 'vendor'],
    static: [],
  };
  return (
    ['# Generated by omnideploy', '.git', '.gitignore', 'Dockerfile', '.dockerignore', '.env', '.env.*', '*.log', '.DS_Store', ...extra[p.lang]].join('\n') + '\n'
  );
}

function renderYaml(p: Project): string {
  const head = `# Render Blueprint — generated by omnideploy. https://render.com/docs/blueprint-spec
services:
  - type: web
    name: ${p.dir}
`;
  if (p.kind === 'static') {
    const build = p.build?.command ? `    buildCommand: npm ci && ${p.build.command}\n` : '';
    const routes = p.spa
      ? `    routes:
      - type: rewrite
        source: /*
        destination: /index.html
`
      : '';
    return `${head}    runtime: static\n${build}    staticPublishPath: ./${p.build?.output ?? '.'}\n${routes}`;
  }
  const common = `    plan: free
    region: oregon
`;
  const tail = `    healthCheckPath: /
    autoDeploy: true
`;
  if (renderUsesDocker(p)) {
    return `${head}    runtime: docker\n${common}    dockerfilePath: ./Dockerfile\n    dockerContext: .\n${tail}`;
  }
  const n = p.renderNative!;
  return `${head}    runtime: ${n.runtime}\n${common}    buildCommand: ${n.build}\n    startCommand: ${n.start}\n${tail}`;
}

const RAILWAY_JSON = `{
  "$schema": "https://railway.com/railway.schema.json",
  "build": {
    "builder": "DOCKERFILE",
    "dockerfilePath": "Dockerfile"
  },
  "deploy": {
    "healthcheckPath": "/",
    "healthcheckTimeout": 300,
    "restartPolicyType": "ON_FAILURE",
    "restartPolicyMaxRetries": 5
  }
}
`;

const VERCEL_JSON = `{
  "$schema": "https://openapi.vercel.sh/vercel.json",
  "rewrites": [
    {
      "source": "/(.*)",
      "destination": "/index.html"
    }
  ]
}
`;

function netlifyToml(p: Project): string {
  const lines = ['# Generated by omnideploy. https://docs.netlify.com/configure-builds/file-based-configuration/', '[build]'];
  lines.push(`publish = "${p.build?.output ?? '.'}"`);
  if (p.build?.command) lines.push(`command = "${p.build.command}"`);
  if (p.lang === 'node') lines.push('', '[build.environment]', 'NODE_VERSION = "22"');
  if (p.spa) lines.push('', '[[redirects]]', 'from = "/*"', 'to = "/index.html"', 'status = 200');
  return lines.join('\n') + '\n';
}

function dockerWhy(p: Project): string {
  return `multi-stage ${LANG_LABEL[p.lang]}${p.framework ? ` (${p.framework})` : ''} image`;
}

/** The files `omnideploy deploy <provider>` would write for this project. */
export function filesFor(p: Project, prov: Provider): GeneratedFile[] {
  const docker = (): GeneratedFile[] => [
    { path: 'Dockerfile', why: dockerWhy(p), contents: p.dockerfile },
    { path: '.dockerignore', why: 'keeps the Docker build context small', contents: dockerignore(p) },
  ];
  switch (prov.id) {
    case 'vercel':
      return p.spa ? [{ path: 'vercel.json', why: 'SPA rewrite so client-side routes work on refresh', contents: VERCEL_JSON }] : [];
    case 'netlify':
      return [{ path: 'netlify.toml', why: 'Netlify build settings' + (p.spa ? ' + SPA redirect' : ''), contents: netlifyToml(p) }];
    case 'github-pages':
      return [];
    case 'railway':
      return [
        ...docker(),
        { path: 'railway.json', why: 'Railway config (build from Dockerfile, health check, restart policy)', contents: RAILWAY_JSON },
      ];
    case 'render': {
      const runtime = p.kind === 'static' ? 'static' : renderUsesDocker(p) ? 'docker' : p.renderNative!.runtime;
      return [
        ...(renderUsesDocker(p) ? docker() : []),
        { path: 'render.yaml', why: `Render Blueprint (${runtime} runtime)`, contents: renderYaml(p) },
      ];
    }
  }
}

function pad(s: string, n: number): string {
  return s + ' '.repeat(Math.max(1, n - s.length));
}

export function buildScenario(projectId: ProjectId, providerId: ProviderId): Scenario {
  const p = project(projectId);
  const prov = provider(providerId);
  const lines: Line[] = [
    { type: 'cmd', text: `cd ${p.dir}` },
    { type: 'cmd', text: `omnideploy deploy ${prov.id}` },
    { type: 'out', text: '┌   omnideploy deploy ', tone: 'note' },
    { type: 'out', text: '│', tone: 'muted', pause: 120 },
    { type: 'out', text: `◆  Detected ${p.detected}`, tone: 'ok', pause: 500 },
    { type: 'out', text: '│', tone: 'muted' },
  ];

  const compat = compatibility(p, prov);
  if (!compat.ok) {
    const alts = PROVIDERS.filter((x) => x.id !== prov.id && compatibility(p, x).ok);
    lines.push(
      { type: 'out', text: `■  ${prov.name}: ${compat.reason}`, tone: 'err', pause: 350 },
      { type: 'out', text: `│  Try: Deploy to ${listOf(alts.map((a) => a.name))} instead.`, tone: 'muted' },
      { type: 'out', text: '', pause: 300 },
      { type: 'out', text: '# stopped before writing or deploying anything · exit 1', tone: 'muted' },
    );
    return { ok: false, lines, files: [], suggestion: alts.at(-1)?.id };
  }

  const files = filesFor(p, prov);
  if (files.length) {
    const width = Math.max(...files.map((f) => f.path.length)) + 2;
    lines.push({ type: 'out', text: '◇  Deployment files to generate', tone: 'step', pause: 300 });
    for (const f of files) {
      lines.push({ type: 'out', text: `│  + ${pad(f.path, width)}— ${f.why} (for ${prov.id})`, tone: 'plain', pause: 160, reveals: f.path });
    }
    lines.push(
      { type: 'out', text: '│', tone: 'muted' },
      { type: 'out', text: '◇  Write these files?  Yes', tone: 'step', pause: 700 },
      { type: 'out', text: '│', tone: 'muted' },
    );
  } else {
    lines.push({ type: 'out', text: '◇  Nothing to generate — no config needed', tone: 'step', pause: 300 });
    lines.push({ type: 'out', text: '│', tone: 'muted' });
  }

  // Providers that build or run the app remotely get the .env.production values first.
  const remote = prov.id === 'render' || prov.id === 'railway' || (prov.id === 'vercel' && p.kind !== 'static');
  if (p.env?.length && remote) {
    lines.push({
      type: 'out',
      text: `◇  .env.production: ${p.env.join(', ')} → set on ${prov.name}`,
      tone: 'step',
      pause: 250,
    });
  }

  if (prov.id === 'render') {
    lines.push(
      { type: 'out', text: '◇  No git remote — created github.com/you/' + p.dir, tone: 'step', pause: 600 },
      { type: 'out', text: `◆  Pushed to https://github.com/you/${p.dir}`, tone: 'ok', pause: 400 },
    );
  }

  const localBuild = p.kind === 'static' && p.build?.command && prov.id !== 'railway' && prov.id !== 'render';
  if (localBuild) {
    lines.push({
      type: 'spin',
      text: `Building · ${p.build!.command}`,
      done: `◇  Built → ${p.build!.output}/ (${p.build!.files} files)`,
      ms: 1500,
      tone: 'step',
    });
  }

  const how: Record<ProviderId, string> = {
    vercel: p.kind === 'static' ? `Uploading ${p.build?.output ?? '.'}/ to Vercel` : 'Uploading source — Vercel builds it',
    netlify: `Uploading ${p.build?.output ?? '.'}/ to Netlify`,
    'github-pages': 'Publishing to GitHub Pages',
    railway: 'railway up — building the Docker image',
    render: `Render is building from github.com/you/${p.dir}`,
  };
  const url = prov.url(p.dir);
  lines.push({
    type: 'spin',
    text: how[prov.id],
    done: `◆  ${prov.name}: ${url}`,
    ms: prov.id === 'render' || prov.id === 'railway' ? 2600 : 1400,
    tone: 'ok',
  });

  lines.push(
    { type: 'out', text: '│', tone: 'muted' },
    { type: 'out', text: '◇  Deployments ────────────────────────────', tone: 'step', pause: 200 },
    { type: 'out', text: `│  ${pad('Provider', 14)}${pad('Status', 8)}URL`, tone: 'muted' },
    { type: 'out', text: `│  ${pad(prov.id, 14)}${pad('ready', 8)}${url}`, tone: 'plain' },
    { type: 'out', text: '│', tone: 'muted' },
    { type: 'out', text: '└  All deployments finished.', tone: 'ok', pause: 200 },
  );

  return { ok: true, lines, files };
}
