import { stringify } from 'yaml';
import type { ArtifactGenerator, DeploymentArtifact, GenerateOptions, ProjectProfile } from '../../../domain/index.js';

/** Languages Render can build natively without a Dockerfile. */
const RENDER_NATIVE: Record<string, string> = { node: 'node', python: 'python', ruby: 'ruby', go: 'go' };

/** Render runs server apps natively when it can, otherwise from a Dockerfile. */
export function renderUsesDocker(profile: ProjectProfile): boolean {
  return profile.kind !== 'static' && (profile.hasDockerfile || !(profile.language in RENDER_NATIVE));
}

/** Install+build command for Render's native runtimes. */
export function renderNativeBuild(p: ProjectProfile): string {
  switch (p.language) {
    case 'node':
      return [p.meta?.install || 'npm install', p.buildCommand].filter(Boolean).join(' && ');
    case 'python': {
      const install =
        p.packageManager === 'poetry' ? 'pip install poetry && poetry install --no-root --only main'
        : p.packageManager === 'uv' ? 'pip install uv && uv sync --frozen --no-dev'
        : 'pip install -r requirements.txt';
      return [install, p.meta?.extraPackages && `pip install ${p.meta.extraPackages}`, p.buildCommand].filter(Boolean).join(' && ');
    }
    case 'ruby':
      return ['bundle install', p.buildCommand].filter(Boolean).join(' && ');
    case 'go':
      return p.buildCommand ?? 'go build -o app .';
    default:
      return p.buildCommand ?? '';
  }
}

export function renderRuntime(p: ProjectProfile): string {
  if (p.kind === 'static') return 'static';
  return renderUsesDocker(p) ? 'docker' : RENDER_NATIVE[p.language]!;
}

export class RenderYamlGenerator implements ArtifactGenerator {
  readonly id = 'render-yaml';
  readonly path = 'render.yaml';

  supports(): boolean {
    return true;
  }

  generate(p: ProjectProfile, opts: GenerateOptions): DeploymentArtifact {
    const runtime = renderRuntime(p);
    const service: Record<string, unknown> = {
      type: 'web',
      name: (opts.providerOptions.serviceName as string | undefined) ?? opts.serviceName,
      runtime,
      plan: (opts.providerOptions.plan as string | undefined) ?? 'free',
      region: (opts.providerOptions.region as string | undefined) ?? 'oregon',
    };
    if (runtime === 'static') {
      if (p.buildCommand) service.buildCommand = p.buildCommand;
      service.staticPublishPath = `./${p.outputDir ?? '.'}`;
      delete service.plan;
      delete service.region;
    } else if (runtime === 'docker') {
      service.dockerfilePath = './Dockerfile';
      service.dockerContext = '.';
    } else {
      service.buildCommand = renderNativeBuild(p);
      service.startCommand = p.startCommand;
    }
    if (runtime !== 'static') {
      service.healthCheckPath = opts.healthCheckPath ?? '/';
      service.autoDeploy = true;
    }
    if (p.kind === 'static' && /^(vite|create-react-app|angular)/.test(p.framework ?? '')) {
      service.routes = [{ type: 'rewrite', source: '/*', destination: '/index.html' }];
    }
    return {
      id: this.id,
      path: this.path,
      contents: '# Render Blueprint — generated by omnideploy. https://render.com/docs/blueprint-spec\n' + stringify({ services: [service] }),
      description: `Render Blueprint (${runtime} runtime)`,
    };
  }
}
