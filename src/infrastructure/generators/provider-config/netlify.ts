import { stringify } from 'smol-toml';
import { isSinglePageApp, type ArtifactGenerator, type DeploymentArtifact, type ProjectProfile } from '../../../domain/index.js';

export class NetlifyTomlGenerator implements ArtifactGenerator {
  readonly id = 'netlify-toml';
  readonly path = 'netlify.toml';

  supports(profile: ProjectProfile): boolean {
    return profile.kind === 'static';
  }

  generate(p: ProjectProfile): DeploymentArtifact {
    const config: Record<string, unknown> = {
      build: { publish: p.outputDir ?? '.', ...(p.buildCommand ? { command: p.buildCommand } : {}) },
    };
    if (p.language === 'node' && p.runtimeVersion) config.build = { ...(config.build as object), environment: { NODE_VERSION: p.runtimeVersion } };
    if (isSinglePageApp(p)) config.redirects = [{ from: '/*', to: '/index.html', status: 200 }];
    return {
      id: this.id,
      path: this.path,
      contents: '# Generated by omnideploy. https://docs.netlify.com/configure-builds/file-based-configuration/\n' + stringify(config) + '\n',
      description: 'Netlify build settings' + (isSinglePageApp(p) ? ' + SPA redirect' : ''),
    };
  }
}
