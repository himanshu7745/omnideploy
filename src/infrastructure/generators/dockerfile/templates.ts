import type { ProjectProfile } from '../../../domain/index.js';

/**
 * Dockerfile templates. Every template:
 *  - is multi-stage (build tools never ship in the runtime image)
 *  - pins the detected runtime version
 *  - runs as a non-root user
 *  - listens on $PORT (set by Render/Railway), defaulting to the detected port
 */
export type DockerTemplate = (p: ProjectProfile) => string;

const HEADER = '# syntax=docker/dockerfile:1\n# Generated by omnideploy — safe to edit; omnideploy will not overwrite it without --force.\n';
const shCmd = (cmd: string) => `CMD ["sh", "-c", ${JSON.stringify(`exec ${cmd}`)}]`;
const lines = (...l: Array<string | false | undefined>) => l.filter((x): x is string => typeof x === 'string').join('\n') + '\n';

/** Serves a static directory with unprivileged nginx on $PORT, with SPA fallback. */
const nginxStage = (from: string, port: number) =>
  lines(
    'FROM nginxinc/nginx-unprivileged:1.27-alpine',
    `ENV PORT=${port}`,
    'USER root',
    `RUN mkdir -p /etc/nginx/templates && printf 'server {\\n  listen \${PORT};\\n  root /usr/share/nginx/html;\\n  location / { try_files $uri $uri/ /index.html; }\\n}\\n' > /etc/nginx/templates/default.conf.template`,
    'RUN rm -f /etc/nginx/conf.d/default.conf && chown -R 101:101 /etc/nginx/conf.d /etc/nginx/templates',
    `COPY --from=${from} --chown=101:101 /out /usr/share/nginx/html`,
    'USER 101',
    `EXPOSE ${port}`,
  );

function nodeImage(p: ProjectProfile): { image: string; user: string; setup?: string } {
  if (p.packageManager === 'bun') return { image: 'oven/bun:1-alpine', user: 'bun' };
  const setup = p.packageManager === 'pnpm' || p.packageManager === 'yarn' ? 'RUN corepack enable' : undefined;
  return { image: `node:${p.runtimeVersion ?? '22'}-alpine`, user: 'node', setup };
}

function nodeInstall(p: ProjectProfile): { copy: string; run: string } {
  const lock = p.meta?.lockfile;
  const copy = `COPY package.json ${lock ? `${lock} ` : ''}./`;
  if (!lock) return { copy, run: p.packageManager === 'npm' || !p.packageManager ? 'npm install' : `${p.packageManager} install` };
  return { copy, run: p.meta?.install || 'npm ci' };
}

const node: DockerTemplate = (p) => {
  const { image, user, setup } = nodeImage(p);
  const install = nodeInstall(p);
  const build = lines(
    `FROM ${image} AS build`,
    'WORKDIR /app',
    setup,
    install.copy,
    `RUN ${install.run}`,
    'COPY . .',
    p.buildCommand && `RUN ${p.buildCommand}`,
  );
  if (p.kind === 'static') {
    return HEADER + build + `RUN cp -r ${p.outputDir ?? 'dist'} /out\n\n` + nginxStage('build', p.port === 3000 ? 8080 : p.port);
  }
  return (
    HEADER +
    build +
    '\n' +
    lines(
      `FROM ${image}`,
      'WORKDIR /app',
      setup,
      `ENV NODE_ENV=production PORT=${p.port}`,
      `COPY --from=build --chown=${user}:${user} /app ./`,
      `USER ${user}`,
      `EXPOSE ${p.port}`,
      shCmd(p.startCommand ?? 'npm start'),
    )
  );
};

const staticSite: DockerTemplate = (p) =>
  HEADER + lines('FROM busybox:1.36 AS files', 'WORKDIR /src', 'COPY . .', `RUN cp -r ${p.outputDir ?? '.'} /out`) + '\n' + nginxStage('files', 8080);

const python: DockerTemplate = (p) => {
  const v = p.runtimeVersion ?? '3.12';
  const extra = p.meta?.extraPackages ? ` ${p.meta.extraPackages}` : '';
  let deps: string;
  if (p.packageManager === 'uv') {
    deps = lines('COPY pyproject.toml uv.lock ./', `RUN pip install uv && uv export --frozen --no-dev --no-hashes --no-emit-project -o requirements.txt && /venv/bin/pip install -r requirements.txt${extra}`);
  } else if (p.packageManager === 'poetry') {
    deps = lines(
      'COPY pyproject.toml poetry.lock* ./',
      `RUN pip install poetry poetry-plugin-export && poetry export --without-hashes --only main -f requirements.txt -o requirements.txt && /venv/bin/pip install -r requirements.txt${extra}`,
    );
  } else {
    // requirements.txt → install deps only (better layer caching); otherwise install the pyproject package from source.
    deps =
      p.meta?.requirements === 'true'
        ? lines('COPY requirements.txt ./', `RUN /venv/bin/pip install -r requirements.txt${extra}`)
        : lines('COPY . .', `RUN /venv/bin/pip install .${extra ? ` && /venv/bin/pip install${extra}` : ''}`);
  }
  return (
    HEADER +
    lines(
      `FROM python:${v}-slim AS deps`,
      'ENV PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1',
      'WORKDIR /app',
      'RUN python -m venv /venv',
    ) +
    deps +
    '\n' +
    lines(
      `FROM python:${v}-slim`,
      `ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PATH=/venv/bin:$PATH PORT=${p.port}`,
      'RUN useradd --create-home --uid 10001 app',
      'WORKDIR /app',
      'COPY --from=deps /venv /venv',
      'COPY --chown=app:app . .',
      'USER app',
      p.buildCommand && `RUN ${p.buildCommand} || echo "omnideploy: build step '${p.buildCommand}' skipped (needs runtime config)"`,
      `EXPOSE ${p.port}`,
      shCmd(p.startCommand ?? 'python main.py'),
    )
  );
};

const java: DockerTemplate = (p) => {
  const v = p.runtimeVersion ?? '21';
  const maven = p.meta?.buildTool !== 'gradle';
  const quarkus = p.meta?.quarkus === 'true';
  const buildImage = maven ? `maven:3.9-eclipse-temurin-${v}` : `gradle:jdk${v}`;
  const build = maven ? 'mvn -B -q -DskipTests package' : `gradle ${p.framework === 'spring-boot' ? 'bootJar' : 'build'} -x test --no-daemon -q`;
  const jarDir = p.meta?.jarDir ?? (maven ? 'target' : 'build/libs');
  const portProp = p.meta?.portProperty;
  const collect = quarkus
    ? `RUN cp -r ${jarDir}/quarkus-app /out`
    : `RUN mkdir /out && cp "$(ls ${jarDir}/*.jar | grep -v -e '-plain.jar$' -e '-sources.jar$' -e '-javadoc.jar$' -e '/original-' | head -n 1)" /out/app.jar`;
  const jar = quarkus ? 'quarkus-run.jar' : 'app.jar';
  return (
    HEADER +
    lines(
      `FROM ${buildImage} AS build`,
      'WORKDIR /src',
      maven ? 'COPY pom.xml ./' : 'COPY build.gradle* settings.gradle* gradle.properties* ./',
      maven ? 'RUN mvn -B -q dependency:go-offline || true' : 'RUN gradle dependencies --no-daemon -q || true',
      'COPY . .',
      `RUN ${build}`,
      collect,
    ) +
    '\n' +
    lines(
      `FROM eclipse-temurin:${v}-jre`,
      'RUN useradd --system --create-home --uid 10001 app',
      'WORKDIR /app',
      'COPY --from=build --chown=app:app /out ./',
      'USER app',
      `ENV PORT=${p.port} JAVA_OPTS="-XX:MaxRAMPercentage=75"`,
      `EXPOSE ${p.port}`,
      shCmd(`java $JAVA_OPTS ${portProp ? `-D${portProp}=$PORT ` : ''}-jar ${jar}`),
    )
  );
};

const go: DockerTemplate = (p) =>
  HEADER +
  lines(
    `FROM golang:${p.runtimeVersion ?? '1.23'}-alpine AS build`,
    'WORKDIR /src',
    'COPY go.mod go.su[m] ./',
    'RUN go mod download',
    'COPY . .',
    `RUN CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o /out/app ${p.meta?.mainPath ?? '.'}`,
  ) +
  '\n' +
  lines(
    'FROM gcr.io/distroless/static-debian12:nonroot',
    'COPY --from=build /out/app /app',
    `ENV PORT=${p.port}`,
    `EXPOSE ${p.port}`,
    'USER nonroot:nonroot',
    'ENTRYPOINT ["/app"]',
  );

const rust: DockerTemplate = (p) => {
  const bin = p.meta?.binName ?? 'app';
  return (
    HEADER +
    lines(`FROM rust:${p.runtimeVersion ?? '1'}-slim AS build`, 'WORKDIR /src', 'COPY . .', `RUN cargo build --release --bin ${bin} && cp target/release/${bin} /out-app`) +
    '\n' +
    lines(
      'FROM debian:bookworm-slim',
      'RUN apt-get update && apt-get install -y --no-install-recommends ca-certificates && rm -rf /var/lib/apt/lists/* \\',
      '  && useradd --system --uid 10001 app',
      'COPY --from=build /out-app /usr/local/bin/app',
      `ENV PORT=${p.port}`,
      'USER app',
      `EXPOSE ${p.port}`,
      'CMD ["app"]',
    )
  );
};

const ruby: DockerTemplate = (p) => {
  const v = p.runtimeVersion ?? '3.3';
  const rails = p.framework === 'rails';
  return (
    HEADER +
    lines(
      `FROM ruby:${v}-slim AS build`,
      'RUN apt-get update && apt-get install -y --no-install-recommends build-essential git libpq-dev libyaml-dev pkg-config && rm -rf /var/lib/apt/lists/*',
      'WORKDIR /app',
      'ENV BUNDLE_WITHOUT="development:test" RAILS_ENV=production RACK_ENV=production',
      'COPY Gemfile Gemfile.loc[k] ./',
      'RUN bundle install --jobs 4',
      'COPY . .',
      rails && 'RUN SECRET_KEY_BASE_DUMMY=1 bundle exec rails assets:precompile',
    ) +
    '\n' +
    lines(
      `FROM ruby:${v}-slim`,
      'RUN apt-get update && apt-get install -y --no-install-recommends libpq5 libyaml-0-2 && rm -rf /var/lib/apt/lists/* \\',
      '  && useradd --create-home --uid 10001 app',
      'WORKDIR /app',
      `ENV BUNDLE_WITHOUT="development:test" RAILS_ENV=production RACK_ENV=production RAILS_LOG_TO_STDOUT=1 RAILS_SERVE_STATIC_FILES=1 PORT=${p.port}`,
      'COPY --from=build /usr/local/bundle /usr/local/bundle',
      'COPY --from=build --chown=app:app /app /app',
      'USER app',
      `EXPOSE ${p.port}`,
      shCmd(p.startCommand ?? 'bundle exec rackup -o 0.0.0.0 -p $PORT'),
    )
  );
};

const php: DockerTemplate = (p) => {
  const v = p.runtimeVersion ?? '8.3';
  const composer = p.meta?.composer === 'true';
  return (
    HEADER +
    (composer
      ? lines(
          'FROM composer:2 AS vendor',
          'WORKDIR /app',
          'COPY composer.json composer.loc[k] ./',
          'RUN composer install --no-dev --no-scripts --no-interaction --prefer-dist --ignore-platform-reqs --optimize-autoloader',
        ) + '\n'
      : '') +
    lines(
      `FROM php:${v}-cli`,
      'RUN docker-php-ext-install pdo pdo_mysql opcache && useradd --create-home --uid 10001 app',
      'WORKDIR /app',
      composer && 'COPY --from=vendor --chown=app:app /app/vendor ./vendor',
      'COPY --chown=app:app . .',
      'USER app',
      `ENV PORT=${p.port}`,
      `EXPOSE ${p.port}`,
      shCmd(p.startCommand ?? `php -S 0.0.0.0:$PORT -t ${p.meta?.docroot ?? '.'}`),
    )
  );
};

const dotnet: DockerTemplate = (p) => {
  const v = p.runtimeVersion ?? '8.0';
  const hasAppUser = Number(v.split('.')[0]) >= 8;
  return (
    HEADER +
    lines(
      `FROM mcr.microsoft.com/dotnet/sdk:${v} AS build`,
      'WORKDIR /src',
      `COPY ${p.meta?.projectFile ?? '*.csproj'} ./`,
      'RUN dotnet restore',
      'COPY . .',
      'RUN dotnet publish -c Release -o /out --no-restore',
    ) +
    '\n' +
    lines(
      `FROM mcr.microsoft.com/dotnet/aspnet:${v}`,
      'WORKDIR /app',
      'COPY --from=build /out .',
      hasAppUser ? 'USER app' : 'RUN useradd --system --uid 10001 app\nUSER app',
      `ENV PORT=${p.port}`,
      `EXPOSE ${p.port}`,
      shCmd(`env ASPNETCORE_URLS=http://+:$PORT ${p.startCommand ?? 'dotnet app.dll'}`),
    )
  );
};

export const DOCKER_TEMPLATES: Partial<Record<ProjectProfile['language'], DockerTemplate>> = {
  node,
  static: staticSite,
  python,
  java,
  go,
  rust,
  ruby,
  php,
  dotnet,
};

const IGNORES: Partial<Record<ProjectProfile['language'], string[]>> = {
  node: ['node_modules', 'npm-debug.log*', '.next', '.nuxt', '.output', 'coverage'],
  python: ['__pycache__', '*.pyc', '.venv', 'venv', '.pytest_cache', '.mypy_cache'],
  java: ['target', 'build', '.gradle', '*.iml', '.idea'],
  go: ['bin', 'vendor'],
  rust: ['target'],
  ruby: ['log/*', 'tmp/*', 'vendor/bundle', '.bundle'],
  php: ['vendor', 'storage/logs/*'],
  dotnet: ['bin', 'obj', 'out'],
};

export function dockerignoreFor(p: ProjectProfile): string {
  return (
    ['# Generated by omnideploy', '.git', '.gitignore', 'Dockerfile', '.dockerignore', '.env', '.env.*', '*.log', '.DS_Store', ...(IGNORES[p.language] ?? [])].join('\n') +
    '\n'
  );
}
